"""tailor: one role -> resume.docx/.pdf, cover_letter.md (DRAFT), ats.json, report.md.

Only SELECTS and REORDERS what facts.yaml already says:
  - summary: the best-matching entry of facts.summaries (or facts.summary)
  - skills: every skill stays; categories and items are ordered by JD weight
  - experience: entries stay in your order; bullets reorder by JD relevance, capped per entry
  - projects: the most relevant few, most relevant first
Nothing is invented. The honesty lock (honesty.py) re-reads the rendered DOCX
and the cover letter and fails the run if any keyword, tech term or number is
not in facts.yaml.
"""
import json
import re
from datetime import date
from pathlib import Path

from . import ats, honesty, render
from .boards import fetch_job
from .keywords import HARD, has
from .profile import corpus, load_facts, load_targets, paths
from .workauth import classify

VARIANTS = [dict(bullets=4, projects=3, coursework=True), dict(bullets=4, projects=2, coursework=True),
            dict(bullets=3, projects=2, coursework=False), dict(bullets=3, projects=1, coursework=False),
            dict(bullets=2, projects=1, coursework=False)]


def slugify(s: str, n: int = 60) -> str:
    return re.sub(r"[^a-z0-9]+", "-", (s or "").lower()).strip("-")[:n] or "role"


def relevance(text: str, w: dict) -> float:
    return sum(v for k, v in w.items() if has(HARD[k], text))


def make_plan(facts: dict, w: dict, v: dict) -> dict:
    summaries = facts.get("summaries") or ([facts["summary"]] if facts.get("summary") else [])
    summary = max(summaries, key=lambda s: relevance(s, w)) if summaries else ""

    skills = facts.get("skills") or {}
    if isinstance(skills, list):
        skills = {"Skills": skills}
    cats = []
    for label, items in skills.items():
        items = [str(i) for i in items or []]
        ordered = sorted(items, key=lambda i: -relevance(i, w))        # stable: ties keep your order
        cats.append((label, ordered, sum(relevance(i, w) for i in items)))
    cats.sort(key=lambda c: -c[2])

    exp = []
    for e in facts.get("experience") or []:
        bl = sorted(e.get("bullets") or [], key=lambda b: -relevance(b, w))[: v["bullets"]]
        exp.append({**e, "bullets": bl})
    projs = sorted(facts.get("projects") or [], key=lambda p: -relevance(p.get("name", "") + " " + " ".join(p.get("bullets") or []), w))
    projs = [{**p, "bullets": sorted(p.get("bullets") or [], key=lambda b: -relevance(b, w))[: max(1, v["bullets"] - 1)]}
             for p in projs[: v["projects"]]]
    edu = [{**e, "coursework": e.get("coursework") if v["coursework"] else None} for e in facts.get("education") or []]
    return {"contact": facts["contact"], "summary": summary, "education": edu,
            "skills": [(c[0], c[1]) for c in cats], "experience": exp, "projects": projs,
            "extra": facts.get("extra") or []}


def cover_letter(facts: dict, plan: dict, w: dict, company: str, title: str) -> tuple[str, str]:
    """(full markdown with DRAFT banner, letter body only for the honesty check)."""
    c = facts["contact"]
    pool = [(b, e.get("title", ""), e.get("org", "")) for e in facts.get("experience") or [] for b in e.get("bullets") or []]
    pool += [(b, p.get("name", ""), "") for p in facts.get("projects") or [] for b in p.get("bullets") or []]
    top = sorted(pool, key=lambda x: -relevance(x[0], w))[:2]
    skills_all = [str(s) for items in (facts.get("skills") or {}).values() for s in items or []] \
        if isinstance(facts.get("skills"), dict) else [str(s) for s in facts.get("skills") or []]
    asked = [s for s in skills_all if relevance(s, w) > 0][:5]
    co = company.strip()
    lines = [f"Dear {co} hiring team,", "",
             f"I am applying for the {title} role at {co}." + (f" In short: {plan['summary']}" if plan["summary"] else ""), ""]
    if top:
        lines.append("Two pieces of my work that match what this role needs:")
        lines.append("")
        for b, where, org in top:
            src = ", ".join(x for x in (where, org) if x)
            lines.append(f"- {b}" + (f" ({src})" if src else ""))
        lines.append("")
    if asked:
        lines.append(f"The skills from my background that this role asks for: {', '.join(asked)}.")
        lines.append("")
    lines += ["[EDIT ME: one or two sentences, in your own words, on why this company and this team. "
              "Only say what is true for you.]", "",
              "Thank you for your time and consideration.", "", "Sincerely,", c["name"],
              " | ".join(x for x in (c.get("email"), c.get("phone")) if x)]
    body = "\n".join(lines)
    banner = ("> DRAFT generated by jobkit from facts.yaml and the job description. Read every line, fill in the "
              "EDIT ME part, and polish it yourself or with your coding agent (see AGENTS.md, section "
              "\"Polishing a cover letter\"). Do not add any skill or number that is not in facts.yaml.\n\n")
    return banner + body + "\n", body


def _from_roles(profile: str, url: str) -> dict | None:
    """Reuse the JD already pulled by discover (full text, real company name) when the URL matches."""
    f = paths(profile)["data"] / "roles.jsonl"
    if not f.exists():
        return None
    key = url.split("#")[0].rstrip("/")
    for line in f.read_text().splitlines():
        try:
            r = json.loads(line)
        except ValueError:
            continue
        if r.get("url", "").rstrip("/") == key and len(r.get("desc") or "") >= 300:
            return {"company": r["company"], "title": r["title"], "desc": r["desc"], "url": url}
    return None


def run(profile: str, url: str | None = None, jd_file: str | None = None, company: str | None = None,
        title: str | None = None, extra_text: str = "") -> int:
    facts = load_facts(profile)
    targets = load_targets(profile)
    facts_text = corpus(facts)
    if url:
        job = _from_roles(profile, url) or fetch_job(url)
        company = company or job["company"]
        title = title or job["title"]
        jd = job["desc"]
    else:
        if not (jd_file and company and title):
            raise SystemExit("give --url, or --jd FILE with --company and --title")
        jd = Path(jd_file).read_text(errors="ignore")
    title = re.sub(r"\s*[\u2013\u2014]\s*", ", ", title).strip()       # no long dashes in our output
    out = paths(profile)["out"] / f"{slugify(company, 30)}_{slugify(title, 50)}"
    out.mkdir(parents=True, exist_ok=True)
    (out / "jd.txt").write_text(f"{title}\n{company}\n{url or jd_file}\n\n{jd}")

    w = ats.jd_weights(jd)
    docx = out / "resume.docx"
    chosen = None
    for v in VARIANTS:
        plan = make_plan(facts, w, v)
        render.build_docx(plan, docx)
        pdf, how = render.to_pdf(docx)
        pages = render.pdf_pages(pdf) if pdf else None
        chosen = (plan, v, pdf, how, pages)
        if pages in (None, 1):
            break
    plan, v, pdf, how, pages = chosen

    text = render.pdf_text(pdf) if pdf else None
    text = text or render.docx_text(docx)
    text = text + extra_text            # used by tests / `check` to prove an injected claim is caught
    report = ats.score(jd, text, facts_text, title)
    auth = classify(jd, targets.get("work_auth", "f1_opt"))

    letter_md, letter_body = cover_letter(facts, plan, w, company, title)
    (out / "cover_letter.md").write_text(letter_md)

    problems = honesty.check(text, facts_text)
    problems += [f"cover letter: {p}" for p in honesty.check(letter_body, facts_text, allow=[company, title, "EDIT ME"])]
    (out / "ats.json").write_text(json.dumps({**report, "work_auth": auth, "pages": pages, "variant": v}, indent=1))
    (out / "plan.json").write_text(json.dumps(plan, indent=1, default=str))

    rep = [f"# {company}: {title}", "", f"Tailored {date.today().isoformat()} from facts.yaml. URL: {url or jd_file}", "",
           f"## ATS score: {report['score']} [{report['band']}]", "",
           f"hard {report['hard']} | title {report['title']} | education {report['education']} | soft {report['soft']} | "
           f"format {report['format']} {report['format_fail'] or ''}", "",
           "Target band is 88 to 97. 98 to 100 reads as keyword stuffing. Below 88 is not fixed by adding words you "
           "cannot back up.", "",
           f"- Matched: {', '.join(report['matched']) or 'none'}",
           f"- In facts.yaml but not shown on this page (ADD by editing selection, truthfully): {', '.join(report['add']) or 'none'}",
           f"- NOT in facts.yaml (GAP, never add unless true; if true, add it to facts.yaml first): {', '.join(report['gap']) or 'none'}",
           "", f"## Work authorization ({targets.get('work_auth')}): {auth['verdict']}", "",
           f"{auth['reason']}" + (f". Note: {auth['note']}" if auth["note"] else ""),
           (f"\n> {auth['evidence']}" if auth["evidence"] else ""), "",
           "## Honesty check: " + ("PASS" if not problems else f"FAIL ({len(problems)})"), ""]
    rep += [f"- {p}" for p in problems] or ["Every keyword, tech term and number in resume and cover letter traces to facts.yaml."]
    rep += ["", "## Files", "", f"- resume.docx", f"- resume.pdf ({how}, pages: {pages})" if pdf else f"- PDF: {how}",
            "- cover_letter.md (DRAFT)", "", "jobkit never submits. Review everything, then apply yourself."]
    (out / "report.md").write_text("\n".join(rep) + "\n")

    print(f"{company}: {title}")
    print(f"  ATS {report['score']} [{report['band']}]  hard {report['hard']} title {report['title']} "
          f"edu {report['education']} soft {report['soft']} format {report['format']}")
    print(f"  GAP (not claimed): {', '.join(report['gap']) or 'none'}")
    print(f"  work auth: {auth['verdict']} ({auth['reason']}){' NOTE: ' + auth['note'] if auth['note'] else ''}")
    print(f"  files: {out}  (pdf: {'yes, ' + str(pages) + ' page(s)' if pdf else how})")
    if problems:
        print(f"HONESTY CHECK FAILED ({len(problems)}):")
        for p in problems:
            print(f"  - {p}")
        print("The draft is NOT safe to use. Remove the claim, or add it to facts.yaml if it is true.")
        return 2
    print("  honesty check: PASS")
    return 0


def check_file(profile: str, path: str, allow: list[str] | None = None) -> int:
    """Honesty-check any edited draft (.docx, .pdf, .md, .txt)."""
    facts_text = corpus(load_facts(profile))
    p = Path(path)
    if p.suffix == ".docx":
        text = render.docx_text(p)
    elif p.suffix == ".pdf":
        text = render.pdf_text(p) or ""
        if not text:
            raise SystemExit("pdftotext not found; check the .docx instead")
    else:
        text = "\n".join(l for l in p.read_text(errors="ignore").splitlines() if not l.startswith(">"))
    allow = (allow or []) + ["EDIT ME"]
    jd = p.parent / "jd.txt"                 # tailor writes title + company on its first two lines
    if jd.exists():
        allow += [l.strip() for l in jd.read_text(errors="ignore").splitlines()[:2] if l.strip()]
    problems = honesty.check(text, facts_text, allow=allow)
    if problems:
        print(f"HONESTY CHECK FAILED for {p.name} ({len(problems)}):")
        for x in problems:
            print(f"  - {x}")
        return 2
    print(f"honesty check: PASS ({p.name})")
    return 0
